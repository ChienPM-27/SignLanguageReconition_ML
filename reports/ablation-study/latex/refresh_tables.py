"""Refresh LaTeX tables from the campaign JSON and verified local artifacts."""

from __future__ import annotations

import csv
import importlib.util
import json
import math
import statistics
from collections import Counter
from datetime import datetime, timedelta, timezone
from pathlib import Path


HERE = Path(__file__).resolve().parent
STUDY = HERE.parent
REPO = STUDY.parent.parent
RUNS = ("F0", "F0-control", "F1", "F2", "F3", "F4")


def tex(value: object) -> str:
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
                    "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
                    "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(replacements.get(char, char) for char in str(value))


def number(value: float, digits: int = 2, signed: bool = False) -> str:
    if not math.isfinite(value):
        raise ValueError("Non-finite report value")
    return format(value, f"{'+' if signed else ''}.{digits}f").replace(".", ",")


def aggregate(values: list[float], scale: float = 100, digits: int = 2) -> str:
    return rf"\({number(statistics.mean(values) * scale, digits)}\pm {number(statistics.pstdev(values) * scale, digits)}\)"


def rows_file(name: str, rows: list[list[str]]) -> None:
    macro = Path(name).stem.capitalize() + "Rows"
    (HERE / "tables" / name).write_text(
        "% Generated by refresh_tables.py; do not edit numerical cells.\n"
        + rf"\newcommand{{\{macro}}}{{" + "\n"
        + "\n".join(" & ".join(row) + r" \\" for row in rows) + "\n}\n", encoding="utf-8")


def main() -> None:
    data = json.loads((STUDY / "RESULTS.json").read_text(encoding="utf-8"))
    spec = importlib.util.spec_from_file_location("ablation_summary", STUDY / "tools/summarize_results.py")
    if spec is None or spec.loader is None:
        raise ImportError("Cannot load the campaign artifact validator")
    validator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(validator)
    records = data["runs"]
    reports, histories, cohorts, audits = {}, {}, {}, {}
    for run, record in records.items():
        if run not in RUNS:
            raise ValueError(f"Unknown campaign run: {run}")
        if record["status"] != "COMPLETED":
            continue
        attempt = Path(record["attempt_path"])
        if not attempt.is_dir():
            attempt = REPO / "artifacts/ablation-study" / run / record["metadata"]["attempt_id"]
        verified = validator.collect_attempt(attempt)
        if verified["status"] != "COMPLETED":
            raise ValueError(f"Run is no longer completed: {run}")
        for key, metric in verified["metrics"].items():
            for field in ("mean", "std"):
                if abs(metric[field] - record["metrics"][key][field]) > 1e-9:
                    raise ValueError(f"Stale RESULTS.json for {run}; rerun summarize_results.py")
        records[run] = verified
        run_dir = Path(verified["summary_path"]).parent
        reports[run], histories[run], cohorts[run] = {}, {}, {}
        for seed in (42, 43, 44):
            seed_dir = run_dir / f"seed_{seed}"
            report = json.loads((seed_dir / "val_report.json").read_text(encoding="utf-8"))
            if report["split_identity"] != "val":
                raise ValueError(f"Expected validation report: {seed_dir}")
            reports[run][seed] = report
            histories[run][seed] = json.loads((seed_dir / "history.json").read_text(encoding="utf-8"))
        for split in ("train", "val", "test"):
            with (attempt / "split_snapshot" / f"{split}.csv").open(encoding="utf-8-sig", newline="") as stream:
                cohorts[run][split] = list(csv.DictReader(stream))
        signer_sets = [{r["participant_id"] for r in cohorts[run][split]} for split in ("train", "val", "test")]
        if any(signer_sets[i] & signer_sets[j] for i in range(3) for j in range(i + 1, 3)):
            raise ValueError(f"Signer leakage in {run}")
        if set(reports[run][42]["sample_membership"]) != {r["sequence_id"] for r in cohorts[run]["val"]}:
            raise ValueError(f"Validation membership differs from split snapshot: {run}")
        with (attempt / "cache_audit/excluded.csv").open(encoding="utf-8-sig", newline="") as stream:
            excluded = list(csv.DictReader(stream))
        audits[run] = {"excluded": excluded, "attempt": attempt}
    completed = [records[run] for run in RUNS if run in reports]
    for key in ("source_commit", "config_sha256", "frozen_split_sha256", "selection_sha256"):
        if len({r["metadata"][key] for r in completed}) > 1:
            raise ValueError(f"Campaign mixes {key}")
    if any(r["class_names"] != completed[0]["class_names"] for r in completed[1:]):
        raise ValueError("Campaign mixes ordered vocabularies")
    cohort_warning = any(r["sample_membership"] != completed[0]["sample_membership"] for r in completed[1:])
    (HERE / "tables").mkdir(exist_ok=True)
    summary, seeds, audit_rows = [], [], []
    for run in RUNS:
        record = records.get(run)
        _, dim = validator.RUNS[run]
        ok = run in reports
        cells = []
        for key in ("top1_accuracy", "top3_accuracy", "macro_f1", "loss"):
            scale, digits = (1, 4) if key == "loss" else (100, 2)
            if ok:
                metric = record["metrics"][key]
                cells.append(rf"\({number(metric['mean'] * scale, digits)}\pm {number(metric['std'] * scale, digits)}\)")
            else:
                cells.append(r"\pending")
        summary.append([tex(run), str(dim), f"{record['seeds_completed'] if record else 0}/3"] + cells
                       + [number(record["training_time_sec_total"] / 60) if ok else r"\pending"])
        for seed in (42, 43, 44):
            if not ok:
                seeds.append([tex(run), str(seed)] + [r"\pending"] * 7)
                continue
            report, history = reports[run][seed], histories[run][seed]
            best = min(range(len(history["val_loss"])), key=history["val_loss"].__getitem__)
            seeds.append([tex(run), str(seed), str(best + 1), str(len(history["val_loss"]))]
                         + [number(report[key] * 100) for key in ("top1_accuracy", "top3_accuracy", "macro_f1")]
                         + [number(report["loss"], 4), number(history["training_time_sec"])])
        if ok:
            counts = [f"{len(cohorts[run][split])} / {len({r['participant_id'] for r in cohorts[run][split]})}"
                      for split in ("train", "val", "test")]
            audit_rows.append([tex(run)] + counts + [str(len(audits[run]["excluded"])), "Đủ 20", "Đã đủ"])
        else:
            audit_rows.append([tex(run)] + [r"\pending"] * 6)
    rows_file("summary.tex", summary)
    rows_file("seeds.tex", seeds)
    rows_file("cohort.tex", audit_rows)
    comparisons = (("F0-control", "F0", "Tắt wrist scale/translation"),
                   ("F1", "F0-control", "Wrist tương đối với thân"), ("F2", "F1", "Palm scale theo clip"),
                   ("F3", "F2", "Chuyển động đầu ngón tay"), ("F4", "F3", "Cosine độ gập ngón tay"))
    comparison_rows = []
    for current, previous, change in comparisons:
        delta = number((records[current]["metrics"]["macro_f1"]["mean"]
                        - records[previous]["metrics"]["macro_f1"]["mean"]) * 100, signed=True) if current in reports and previous in reports else r"\pending"
        comparison_rows.append([tex(current) + " so với " + tex(previous), tex(change), delta])
    rows_file("comparisons.tex", comparison_rows)
    paired = []
    if all(run in reports for run in ("F0", "F0-control")):
        for seed in (42, 43, 44):
            paired.append([str(seed)] + [number((reports["F0-control"][seed][key] - reports["F0"][seed][key]) * (1 if key == "loss" else 100), 4 if key == "loss" else 2, True)
                                           for key in ("top1_accuracy", "top3_accuracy", "macro_f1", "loss")])
    rows_file("paired.tex", paired)
    signer_rows = []
    baseline = reports.get("F0", {}).get(42)
    if baseline and "F0-control" in reports:
        for participant in sorted(baseline["per_participant_accuracy"]):
            values = [[r["per_participant_accuracy"][participant]["accuracy"] for r in reports[run].values()]
                      for run in ("F0", "F0-control")]
            signer_rows.append([tex(participant), str(baseline["per_participant_accuracy"][participant]["samples"]), aggregate(values[0]), aggregate(values[1]), number((statistics.mean(values[1])-statistics.mean(values[0]))*100, signed=True)])
    rows_file("signers.tex", signer_rows)
    gloss_rows, gloss_deltas = [], {}
    if baseline and "F0-control" in reports:
        support = Counter(row["gloss"] for row in cohorts["F0"]["val"])
        for i, gloss in enumerate(baseline["class_names"]):
            values = {}
            for run in ("F0", "F0-control"):
                values[run] = []
                for report in reports[run].values():
                    cm = report["confusion_matrix"]
                    true_count, predicted_count = sum(cm[i]), sum(row[i] for row in cm)
                    values[run].append(2 * cm[i][i] / (true_count + predicted_count) if true_count + predicted_count else 0)
            a, b = (statistics.mean(values[run]) for run in ("F0", "F0-control"))
            gloss_deltas[gloss] = (b-a)*100
            gloss_rows.append([tex(gloss), str(support[gloss]), number(a*100), number(b*100), number((b-a)*100, signed=True)])
    rows_file("glosses.tex", gloss_rows)
    macros = {"ReportDate": datetime.now(timezone(timedelta(hours=7))).strftime("%d/%m/%Y"),
              "CompletedConfigs": str(len(completed)), "CompletedModels": str(sum(r["seeds_completed"] for r in completed)),
              "CohortWarning": "Cohort validation khác nhau; cần matched-cohort comparison trước khi kết luận." if cohort_warning else "Cohort validation của các cấu hình đã hoàn tất khớp nhau."}
    waiting = [run for run in RUNS if run not in reports]
    macros["PendingSummary"] = "Chờ kết quả đủ điều kiện: " + ", ".join(waiting) + "." if waiting else "Đã nhận đủ kết quả của sáu cấu hình."
    for run, macro in (("F1", "RunOneOutcome"), ("F2", "RunTwoOutcome"), ("F3", "RunThreeOutcome"), ("F4", "RunFourOutcome")):
        macros[macro] = ("Đã đủ 3 seeds; Macro-F1 " + number(records[run]["metrics"]["macro_f1"]["mean"] * 100) + r"\%."
                         if run in reports else r"\pending; chờ 3 seeds và audit.")
    for run, prefix in (("F0", "Baseline"), ("F0-control", "Control")):
        if run in reports:
            macros[prefix + "Fone"] = number(records[run]["metrics"]["macro_f1"]["mean"] * 100)
            metadata = records[run]["metadata"]
            macros[prefix + "Attempt"] = tex(metadata["attempt_id"])
            local_times = [datetime.fromisoformat(metadata[key]).astimezone(timezone(timedelta(hours=7))).strftime("%d/%m/%Y %H:%M:%S")
                           for key in ("started_at_utc", "ended_at_utc")]
            macros[prefix + "Window"] = " -- ".join(local_times)
    if baseline and "F0-control" in reports:
        macros["FoneDelta"] = number((records["F0-control"]["metrics"]["macro_f1"]["mean"]-records["F0"]["metrics"]["macro_f1"]["mean"])*100, signed=True)
        macros["PositiveSeeds"] = str(sum(reports["F0-control"][seed]["macro_f1"] > reports["F0"][seed]["macro_f1"] for seed in (42, 43, 44)))
        for key, reverse in (("GlossGains", True), ("GlossDeclines", False)):
            selected = sorted(gloss_deltas, key=gloss_deltas.__getitem__, reverse=reverse)[:3]
            macros[key] = "; ".join(f"{tex(g)} ({number(gloss_deltas[g], signed=True)} điểm)" for g in selected)
    if completed:
        first = completed[0]
        for key, macro in (("source_commit", "SourceCommit"), ("checkout_commit", "CheckoutCommit"),
                           ("config_sha256", "ConfigHash"), ("frozen_split_sha256", "SplitHash"), ("selection_sha256", "SelectionHash")):
            value = first["metadata"][key]
            macros[macro] = r"\texttt{" + value[:32] + r"}\newline\texttt{" + value[32:] + "}" if len(value)>40 else r"\texttt{" + value + "}"
        value = first["preprocess_identity"]
        macros["PreprocessHash"] = r"\texttt{" + value[:32] + r"}\newline\texttt{" + value[32:] + "}"
    (HERE / "data.tex").write_text("% Generated from verified artifacts.\n" + "\n".join(
        rf"\newcommand{{\{key}}}{{{value}}}" for key, value in macros.items()) + "\n", encoding="utf-8")
    snapshot = {"report_date": macros["ReportDate"], "completed_configs": len(completed),
                "completed_models": sum(r["seeds_completed"] for r in completed), "cohort_warning": cohort_warning,
                "inputs": [{"run": run, "attempt": str(audit["attempt"])} for run, audit in audits.items()]}
    (HERE / "report_snapshot.json").write_text(json.dumps(snapshot, indent=2, ensure_ascii=False)+"\n", encoding="utf-8")
    print(f"Verified {len(completed)} configurations; refreshed LaTeX tables in {HERE}")


if __name__ == "__main__":
    main()
